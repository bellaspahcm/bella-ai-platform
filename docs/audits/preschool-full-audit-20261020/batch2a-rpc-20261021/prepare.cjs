const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const d=__dirname,prior=path.join(d,'../batch2a');
const canon=x=>Array.isArray(x)?x.map(canon):x&&typeof x==='object'?Object.fromEntries(Object.keys(x).sort().map(k=>[k,canon(x[k])])):x;
const parse=f=>JSON.parse(fs.readFileSync(f,'utf8').replace(/^\uFEFF/,''));
const pre=parse(path.join(d,'tables-pre-cli.json')).rows[0].evidence;
assert.deepEqual(canon(pre),canon(parse(path.join(prior,'production-pre-fingerprint.json'))),'STOP:32-table baseline drift');
const rpc=parse(path.join(d,'rpc-pre.json'));
assert.equal(rpc.function.owner,'postgres');assert(rpc.function.security_definer);
assert(rpc.roles.find(r=>r.name==='anon').execute);assert(rpc.roles.find(r=>r.name==='postgres').bypass_rls);
assert.equal(rpc.dynamic_candidates.length,1);assert.equal(rpc.dynamic_candidates[0].name,'exec_sql');assert.equal(rpc.incoming_function_references.length,0);
assert(!rpc.memberships.some(m=>m.member==='anon'),'STOP:anon has inherited role path');
for(const name of ['fingerprint-query.sql','fingerprint-readonly.sql'])fs.copyFileSync(path.join(prior,name),path.join(d,name));
fs.writeFileSync(path.join(d,'production-pre-fingerprint.json'),JSON.stringify(pre,null,2)+'\n');
let bootstrap=fs.readFileSync(path.join(prior,'bootstrap-rehearsal.cjs'),'utf8');
fs.writeFileSync(path.join(d,'bootstrap-rehearsal.cjs'),bootstrap);
let rehearsal=fs.readFileSync(path.join(prior,'rehearse.cjs'),'utf8');
fs.writeFileSync(path.join(d,'rehearse.cjs'),rehearsal);
fs.writeFileSync(path.join(d,'drift-check.json'),JSON.stringify({checkedAt:new Date().toISOString(),exact32TableFingerprintUnchanged:true,anonymousParentMemberships:0,anonymousDynamicExecutors:['public.exec_sql(text)'],incomingRpcReferences:0},null,2)+'\n');
console.log(JSON.stringify({exact32TableFingerprintUnchanged:true,roles:rpc.roles.length,additionalRpcAuthorityRecorded:true}));
